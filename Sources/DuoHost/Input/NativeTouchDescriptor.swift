import Foundation
import DuoCore

enum NativeTouchDescriptor {
    static func descriptor() -> Data {
        let maximumContacts = NativeTouchFrame.maximumContacts
        let finger: [UInt8] = [
            0x05, 0x0D, 0x09, 0x22, 0xA1, 0x02,
            0x09, 0x42, 0x09, 0x47, 0x15, 0x00, 0x25, 0x01, 0x75, 0x01, 0x95, 0x02, 0x81, 0x02,
            0x75, 0x06, 0x95, 0x01, 0x81, 0x03,
            0x09, 0x51, 0x25, 0x7F, 0x75, 0x08, 0x95, 0x01, 0x81, 0x02,
            0x05, 0x01, 0x09, 0x30, 0x09, 0x31,
            0x16, 0x00, 0x00, 0x26, 0xFF, 0x7F,
            0x75, 0x10, 0x95, 0x02, 0x81, 0x02, 0xC0
        ]
        return Data([0x05, 0x0D, 0x09, 0x04, 0xA1, 0x01, 0x85, 0x01]
                    + Array(repeating: finger, count: maximumContacts).flatMap { $0 }
                    + [0x05, 0x0D, 0x09, 0x54, 0x15, 0x00, 0x25, UInt8(maximumContacts),
                       0x75, 0x08, 0x95, 0x01, 0x81, 0x02,
                       0x85, 0x02, 0x09, 0x55, 0x75, 0x08, 0x95, 0x01, 0xB1, 0x02, 0xC0])
    }

    static func contactReport(_ contact: NativeTouchContact, identifier: UInt8, isDown: Bool) -> [UInt8] {
        let x = UInt16((min(1, max(0, contact.x)) * 32767).rounded())
        let y = UInt16((min(1, max(0, contact.y)) * 32767).rounded())
        // TouchValid keeps both the press and lift classified as a finger.
        return [isDown ? 0x03 : 0x02, identifier, UInt8(x & 255), UInt8(x >> 8), UInt8(y & 255), UInt8(y >> 8)]
    }
}
